#!/usr/bin/env python3
"""Generate deploy/error-pages/sensitive-paths.yaml from a pinned OWASP CRS list plus our own rules (rules.yaml).

  build.py --check            exit 1 if the committed manifest differs from what the inputs generate
  build.py --write            regenerate the manifest
  build.py --update VERSION   download that CRS release, pin it in rules.yaml and regenerate
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DATA = HERE / "crs-restricted-files.data"
RULES = HERE / "rules.yaml"
MANIFEST = ROOT / "deploy/error-pages/sensitive-paths.yaml"
PRIORITY = 100000  # app/k8s_manifests.py SENSITIVE_PATHS_OPT_OUT_PRIORITY must stay above this
CRS_URL = "https://raw.githubusercontent.com/coreruleset/coreruleset/{version}/rules/restricted-files.data"

HEADER = """\
# GENERATED by scripts/sensitive_paths/build.py. Do not edit: change scripts/sensitive_paths/rules.yaml and regenerate.
# Answers 404 at the edge for paths that hold secrets and that no public app should serve: scanners probe every host for
# them. No host, so it covers every app, custom domains and the platform itself. Traefik sends these to the error-pages
# service, whose static file server has no such file. Docs: docs/OPERATIONS.md "Sensitive paths".
# An app that really serves such paths opts out (allow_sensitive_paths): its Ingress gets a higher router.priority.
# The regex must start with "/" (Kubernetes validates that), and matches whole path segments at any depth, so
# /repo.git, /.github and /.well-known are untouched. ";" also ends a segment, for servers that strip path parameters.
"""


def crs_entries(text: str) -> list[str]:
    """Dotfile entries of the CRS list, in file order, without duplicates or comments."""
    rows = (line.strip() for line in text.splitlines())
    return list(dict.fromkeys(r for r in rows if r.startswith(".")))


def fragment(entry: str) -> str:
    """CRS matches anywhere in a path; we match whole segments, which is stricter and safer in front of every app."""
    name = entry.rstrip("/")
    if name.startswith(".sql."):  # dump suffixes: backup.sql.gz
        return "[^/]*" + re.escape(name)
    if name[-1] in "_-":  # prefixes: .bash_, .oh-my-
        return re.escape(name) + "[^/]*"
    return re.escape(name)


def build_regex(crs_text: str, rules: dict) -> str:
    skip = set(rules.get("skip") or [])
    parts = [fragment(e) for e in crs_entries(crs_text) if e not in skip]
    parts = list(dict.fromkeys(parts)) + list(rules.get("extra") or [])
    return "/(?i:" + "|".join(parts) + ")([/;]|$)"


def build_manifest(crs_text: str, rules: dict) -> str:
    return HEADER + f"""\
# Sources: OWASP CRS {rules["crsVersion"]} (Apache-2.0, see scripts/sensitive_paths/NOTICE) and our own additions.
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: sensitive-paths
  namespace: picopaas-system
  annotations:
    traefik.ingress.kubernetes.io/router.pathmatcher: PathRegexp
    traefik.ingress.kubernetes.io/router.priority: "{PRIORITY}"
spec:
  ingressClassName: traefik
  rules:
    - http:
        paths:
          - path: {build_regex(crs_text, rules)}
            pathType: ImplementationSpecific
            backend:
              service:
                name: error-pages
                port:
                  number: 80
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--update", metavar="VERSION")
    args = ap.parse_args()

    if args.update:
        if not re.fullmatch(r"v\d+\.\d+\.\d+", args.update):
            ap.error("VERSION looks like v4.30.0")
        with urllib.request.urlopen(CRS_URL.format(version=args.update), timeout=30) as resp:  # noqa: S310 - fixed https host
            DATA.write_bytes(resp.read())
        RULES.write_text(re.sub(r"(?m)^crsVersion: .*$", f"crsVersion: {args.update}", RULES.read_text()))

    wanted = build_manifest(DATA.read_text(), yaml.safe_load(RULES.read_text()))
    if args.check:
        if MANIFEST.read_text() != wanted:
            print(f"{MANIFEST} is out of date: run build.py --write", file=sys.stderr)
            return 1
        return 0
    MANIFEST.write_text(wanted)
    return 0


if __name__ == "__main__":
    sys.exit(main())
